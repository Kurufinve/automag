#!/usr/bin/env python
"""
automag.tools.write_ninja_deps
==============================

Emit the ``include``d fragment of ``build.ninja`` that lists every source file
the executable is built from.

Ninja has no globbing, so ``build.ninja`` includes this generated file and
declares it with ``generator = 1``; ninja regenerates it whenever the tree
changes and restarts the build automatically.

    python tools/write_ninja_deps.py > build/deps.ninja
    python tools/write_ninja_deps.py --output build/deps.ninja

.. codeauthor:: Automag contributors
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Directories whose ``*.py`` files end up inside the bundle.
SOURCE_DIRECTORIES = (
    "0_conv_tests",
    "1_lin_response",
    "2_coll",
    "2_relax",
    "3_monte_carlo",
    "4_mae",
    "common",
    "calculators",
    "pipeline",
    "tools",
)

#: Single files that always matter.
SOURCE_FILES = ("run_automag.py", "input_automag.py", "requirements.txt")


def _escape(path):
    return str(path).replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=None,
                        help="write here instead of stdout (creates parents)")
    args = parser.parse_args(argv)

    files = []
    for name in SOURCE_FILES:
        path = ROOT / name
        if path.is_file():
            files.append(path)
    for name in SOURCE_DIRECTORIES:
        directory = ROOT / name
        if not directory.is_dir():
            continue
        files.extend(sorted(item for item in directory.rglob("*.py")
                            if "__pycache__" not in item.parts))
    for name in ("geometries",):
        directory = ROOT / name
        if directory.is_dir():
            files.extend(sorted(item for item in directory.iterdir()
                                if item.is_file()))

    unique = sorted({str(item) for item in files})
    lines = [
        "# Generated by tools/write_ninja_deps.py - do not edit.",
        "code_files = " + " ".join(_escape(item) for item in unique),
    ]
    text = "\n".join(lines) + "\n"
    if args.output:
        destination = Path(args.output)
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
