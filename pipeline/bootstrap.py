"""
automag.pipeline.bootstrap
==========================

First-run helper: when automag is started in a directory that holds nothing but
a structure file, write a default ``input_automag.py`` and use it.

The generated file is the plan of ``examples/prophet``: the magnetic search
(``2_coll``) evaluated with the bundled Prophet-V1-Mag model, which needs no DFT
code and no cluster.  The magnetocrystalline anisotropy (``4_mae``) is left out
on purpose - the released Prophet weights are isotropic in the moment
direction, so the MAE would be zero; add the stage (see
``examples/prophet_mae/``) only with a direction-sensitive model or a DFT code.

The file is a normal input file - edit it to change the calculator, the stages
or the parameters.

Only the absence of *any* ``input_automag.{py,yaml,json}`` triggers this, and
the file is never overwritten.

.. codeauthor:: Automag contributors
"""
from __future__ import annotations

from pathlib import Path

#: Names searched for a structure, in this order.
STRUCTURE_PATTERNS = ("structure.vasp", "POSCAR", "*.vasp", "*.cif", "*.poscar")

#: Name of the generated controlling file.
CONFIG_NAME = "input_automag.py"

TEMPLATE = '''\
"""
{title}

Generated by automag because this directory had no input_automag.* file - only
``{structure}``.  Edit freely: any calculator, stage or parameter can be
changed, and ``automag --help`` lists the run modes.
"""

import os

PROPHET_PARAMS = {{
    # The checkpoints ship with automag (<repo>/models, also inside the frozen
    # bundle); PROPHET_MODEL / PROPHET_HEAD still override them.
    "model_path": os.environ.get("PROPHET_MODEL"),
    "head_path": os.environ.get("PROPHET_HEAD"),
    "device": os.environ.get("PROPHET_DEVICE", "cpu"),
    # True = predict the moments first and evaluate the energy for them
    # (two-step mode, see examples/prophet_moments/).
    "predict_moments": False,
}}

PROPHET_SUBMIT = {{
    "use_fireworks": False,
    "parallel_over_configurations": True,
    # No batch directives: the calculations run as plain processes here.
    "jobheader": "#!/bin/bash",
}}

PIPELINE = {{
    "workdir": ".",
    "structure": "{structure}",
    "struct_suffix": "",

    "wait_timeout": 30 * 24 * 3600,
    "wait_interval": 30,
    "wait_stable_seconds": 60,

    "run": [
        {{
            "id": "coll",
            "stage": "coll",
            "calculator": "prophet_spin",
            "description": "collinear magnetic configurations with prophet",
            "params": PROPHET_PARAMS,
            "supercell_size": 1,
            **PROPHET_SUBMIT,
        }},
    ],
}}

'''


def find_structure(directory: Path | None = None):
    """Return the structure file to use, or ``None`` when there is none."""
    directory = Path(directory or Path.cwd())
    for pattern in STRUCTURE_PATTERNS:
        for path in sorted(directory.glob(pattern)):
            if path.is_file() and path.stat().st_size > 0:
                return path
    return None


def ensure_config(directory: Path | None = None, structure: Path | None = None):
    """Create ``input_automag.py`` when the directory only has a structure.

    Returns the created file, or ``None`` when nothing was written (an input
    file already exists, or there is no structure to work with).
    """
    directory = Path(directory or Path.cwd()).resolve()
    if any((directory / f"{Path(CONFIG_NAME).stem}{suffix}").is_file()
           for suffix in (".py", ".yaml", ".yml", ".json")):
        return None

    structure = Path(structure) if structure else find_structure(directory)
    if structure is None:
        return None

    name = structure.name
    title = f"Prophet magnetic search for {name} (automag default plan)"
    target = directory / CONFIG_NAME
    target.write_text(TEMPLATE.format(title=title, structure=name))
    print(f"No input file found: wrote a default plan to {target}")
    print(f"  structure: {name}")
    print("  stages:    coll (prophet_spin)")
    try:
        import prophet_spin  # noqa: F401
    except Exception:  # noqa: BLE001 - the build may lack torch/prophet_spin
        print("  WARNING: this automag cannot run prophet_spin (built with")
        print("           --no-prophet or the package is not installed).")
        print("           Edit the file and pick a calculator that is")
        print("           available, or use a build that includes prophet.")
    print("  note: 4_mae is not in the default plan - the released Prophet")
    print("        model is isotropic, so MAE would be zero. See")
    print("        examples/prophet_mae/ to add it deliberately.")
    return target